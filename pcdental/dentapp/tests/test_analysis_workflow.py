    def test_dentist_sees_only_own_patients(self):
        client = APIClient()
        client.force_authenticate(user=self.dentist_b.dentist)
        resp = client.get('/dental-reports/')
        self.assertEqual(resp.status_code, 200)
        self.assertEqual(len(resp.data), 0)

